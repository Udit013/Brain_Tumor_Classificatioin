"""Assemble the Hugging Face Space folder (mirrors the repo layout the package expects).

    python deploy/hf_space/build.py            # -> build/hf_space/
    hf upload Udit013/brain-tumor-mri-classifier build/hf_space . --repo-type space

Contents: app.py, README.md (Space config), requirements.txt (runtime pins from
requirements-app.txt), src/ (neuroclass + btc), the verified serving bundle,
measured metrics, the bge-small literature index and the example images.
Checksums of the bundle are verified by the app at load time (manifest.json).
"""

from __future__ import annotations

import json
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
HERE = Path(__file__).resolve().parent
OUT = ROOT / "build" / "hf_space"
INDEX_MODEL = "BAAI/bge-small-en-v1.5"
# Pins that must differ on the Space to satisfy gradio[mcp]; the platform test
# suite is run against these in CI (job "space").
SPACE_OVERRIDES = {"pydantic": "pydantic==2.12.5"}


def latest_index() -> Path:
    tag = INDEX_MODEL.split("/")[-1]
    found = sorted(p for p in (ROOT / "data" / "rag_index").glob(f"*-{tag}-*") if p.is_dir())
    if not found:
        raise SystemExit(f"no {INDEX_MODEL} index; run python -m neuroclass.rag.index build")
    return found[-1]


def requirements() -> str:
    lines = ["# Generated by deploy/hf_space/build.py from requirements-app.txt: runtime pins",
             "# only (no test tools, no paid-LLM SDK). HF Spaces also installs",
             "# gradio[oauth,mcp]==<sdk_version>, whose mcp extra pins pydantic<=2.12.5 and mcp<2."]
    for line in (ROOT / "requirements-app.txt").read_text().splitlines():
        if line.startswith("# test-only"):
            break
        # anthropic: paid, never used on the Space. mcp: a local stdio tool, and
        # gradio[mcp] (installed by HF) pins mcp<2.
        if line and not line.startswith("#") and not line.startswith(("anthropic", "mcp==")):
            lines.append(SPACE_OVERRIDES.get(line.split("==")[0], line))
    return "\n".join(lines) + "\n"


def main() -> None:
    import sys

    if "--requirements-only" in sys.argv:          # CI: dependency check without the bundle
        OUT.mkdir(parents=True, exist_ok=True)
        (OUT / "requirements.txt").write_text(requirements())
        return
    if OUT.exists():
        shutil.rmtree(OUT)
    OUT.mkdir(parents=True)
    shutil.copy2(HERE / "app.py", OUT / "app.py")
    shutil.copy2(HERE / "README.md", OUT / "README.md")
    (OUT / "requirements.txt").write_text(requirements())
    ignore = shutil.ignore_patterns("__pycache__", "*.pyc")
    for pkg in ("neuroclass", "btc"):
        shutil.copytree(ROOT / "src" / pkg, OUT / "src" / pkg, ignore=ignore)
    shutil.copytree(ROOT / "models" / "serving", OUT / "models" / "serving")
    shutil.copy2(ROOT / "models" / "registry.json", OUT / "models" / "registry.json")
    shutil.copytree(ROOT / "results" / "metrics", OUT / "results" / "metrics", ignore=ignore)
    (OUT / "results" / "rag").mkdir(parents=True)
    for f in (ROOT / "results" / "rag").glob("*.json"):
        shutil.copy2(f, OUT / "results" / "rag" / f.name)
    shutil.copytree(ROOT / "space" / "examples", OUT / "space" / "examples")
    idx = latest_index()
    shutil.copytree(idx, OUT / "data" / "rag_index" / idx.name)
    manifest = json.loads((ROOT / "models" / "serving" / "manifest.json").read_text())
    size = sum(f.stat().st_size for f in OUT.rglob("*") if f.is_file()) / 1e6
    print(f"built {OUT.relative_to(ROOT)}: model {manifest['model_version']}, index {idx.name}, "
          f"{size:.0f} MB")


if __name__ == "__main__":
    main()
